test('slugify', () => {
  assert.equal(slugify('FINE ART Paper & Stationery'), 'fine-art-paper-and-stationery')
  assert.equal(slugify('  Café 8½ x 11"  '), 'cafe-81-2-x-11')
})

test('catalog: one product per Retail family, one variant per row', () => {
  const catalog = buildCatalog(catalogInput)
  assert.deepEqual(catalog.products.map((p) => p.retailId), ['p1', 'p3'])
  assert.deepEqual(catalog.variants.map((v) => [v.sku, v.productRetailId]), [['100', 'p1'], ['101', 'p1'], ['200', 'p3']])
  assert.deepEqual(catalog.brands, [{ retailId: 'b1', name: 'Hammermill', slug: 'hammermill' }])
})

test('catalog: eCom supplies name, slug, visibility, categories and tags', () => {
  const [bond, envelope] = buildCatalog(catalogInput).products
  assert.equal(bond.name, 'Bond Paper 20lb')
  assert.equal(bond.slug, 'bond-paper-20lb')
  assert.equal(bond.ecwidProductId, 900)
  assert.equal(bond.isEnabled, true)
  assert.equal(bond.defaultEcwidCategoryId, 51)
  assert.equal(bond.searchTags, 'BOND, STOCKED')
  assert.equal(bond.brandRetailId, 'b1')
  // Not in eCom: falls back to the POS flags and product type.
  assert.equal(envelope.isEnabled, false)
  assert.equal(envelope.slug, 'envelope')
  assert.equal(envelope.defaultEcwidCategoryId, 51)
})

test('catalog: unknown categories are dropped; duplicate slugs get a suffix', () => {
  const catalog = buildCatalog(catalogInput)
  assert.deepEqual(catalog.productCategories.filter((c) => c.productRetailId === 'p1').map((c) => c.ecwidCategoryId), [50, 51])
  assert.deepEqual(catalog.categories.map((c) => c.slug), ['paper', 'bond', 'bond-52'])
  assert.equal(catalog.categories[1].parentEcwidCategoryId, 50)
  assert.equal(catalog.categories[2].isHidden, true)
  assert.equal(catalog.categories[0].imageSourceUrl, 'https://cdn/cat.jpg')
})

test('catalog: variant details, default variant and stock', () => {
  const catalog = buildCatalog(catalogInput)
  const [ream, box] = catalog.variants
  assert.equal(ream.name, 'REAM / WHITE')
  assert.equal(ream.price, 10.12345)
  assert.equal(ream.barcode, '0123')
  assert.equal(ream.weightLb, 5)
  assert.equal(ream.ecwidCombinationId, 701)
  assert.equal(ream.isDefault, false)
  assert.equal(box.isDefault, true) // eCom's default combination
  assert.equal(box.isEnabled, false)
  assert.deepEqual(catalog.variantOptions.filter((o) => o.variantRetailId === 'p1'), [
    { variantRetailId: 'p1', name: 'UOM', value: 'REAM', sortOrder: 0 },
    { variantRetailId: 'p1', name: 'COLOR', value: 'WHITE', sortOrder: 1 },
  ])
  assert.deepEqual(catalog.inventory.map((i) => [i.variantRetailId, i.qtyOnHand, i.reorderPoint]), [['p1', 7, 2], ['p2', -1, null], ['p3', 0, null]])
})

