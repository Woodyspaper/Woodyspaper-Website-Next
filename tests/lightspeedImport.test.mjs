test('pricing: price lists, skipped lines, group lists and group discounts', () => {
  const result = buildPricing({
    variantRetailIds: new Set(['p1', 'p2']),
    priceBooks: [
      { id: 'base', name: 'General Price Book (All Products)', type: 'BASE' },
      { id: 'k1', name: 'ACME | 123 | T1', type: 'GENERAL', customer_group_id: 'g9', restrict_to_platform_label: 'In Store' },
    ],
    priceBookProducts: [
      { price_book_id: 'base', product_id: 'p1', price: 10 },
      { price_book_id: 'k1', product_id: 'p1', price: 7.5, version: 1 },
      { price_book_id: 'k1', product_id: 'p1', price: 7.25, version: 2 },
      { price_book_id: 'k1', product_id: 'p2', price: 0 },
      { price_book_id: 'k1', product_id: 'gone', price: 4 },
    ],
    promotions: [
      {
        name: 'TIER 1 WHOLESALE', status: 'active', use_promo_code: false, customer_group_ids: ['g1'],
        action: { type: 'basic_percent_discount', value: 0.28 }, condition: { include: [], exclude: [{ field: 'type_id', value: 't-carbonless' }] },
      },
      { name: 'GOV 2', status: 'active', customer_group_ids: ['g2'], action: { type: 'basic_percent_discount', value: 0.375 }, condition: {} },
      { name: 'Coupon', status: 'active', use_promo_code: true, customer_group_ids: ['g1'], action: { type: 'basic_percent_discount', value: 0.9 } },
      { name: 'Old', status: 'inactive', customer_group_ids: ['g1'], action: { type: 'basic_percent_discount', value: 0.5 } },
    ],
  })
  assert.deepEqual(result.priceLists, [{ retailId: 'k1', name: 'ACME | 123 | T1', platform: 'In Store' }])
  assert.deepEqual(result.priceListItems, [{ priceListRetailId: 'k1', variantRetailId: 'p1', price: 7.25 }])
  assert.deepEqual(result.skipped, { otherBook: 1, unknownProduct: 1, zeroPrice: 1, duplicate: 1 })
  assert.deepEqual([...result.groupPriceLists], [['g9', 'k1']])
  assert.deepEqual(result.groupDiscounts.get('g1'), { percent: 28, name: 'TIER 1 WHOLESALE', excludedCategoryRetailIds: ['t-carbonless'] })
  assert.equal(result.groupDiscounts.get('g2').percent, 37.5)
})
