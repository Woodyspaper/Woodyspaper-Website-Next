import { storeApiEnabled, storeApiGet } from './storeApi'

/**
 * Search-as-you-type product lookups against Lightspeed's (Ecwid) product API,
 * through the public token (see storeApi.ts). Without that token the feature
 * switches off quietly and the search box still runs full searches.
 */

export type ProductSuggestion = {
  id: number
  name: string
  sku: string
  price: string
  inStock: boolean
  /** Small product photo, or '' when the product has none. */
  image: string
  /** Store route for the product, e.g. "#!/napkin-lunch-white/p/866396123". */
  route: string
}

export type SuggestionResults = {
  total: number
  items: ProductSuggestion[]
}

type ApiProduct = {
  id: number
  name: string
  sku?: string
  autogeneratedSlug?: string
  customSlug?: string
  defaultDisplayedPriceFormatted?: string
  inStock?: boolean
  smallThumbnailUrl?: string
  thumbnailUrl?: string
}

/** Only ask the API for what the dropdown shows, which keeps each reply around 1–2 KB. */
const FIELDS =
  'total,items(id,name,sku,autogeneratedSlug,customSlug,defaultDisplayedPriceFormatted,inStock,smallThumbnailUrl,thumbnailUrl)'

export const SUGGESTION_LIMIT = 8
export const MIN_QUERY_LENGTH = 2
/** Longest search text the site accepts, from the box or a ?q= link. */
export const MAX_QUERY_LENGTH = 100

export const suggestionsEnabled = storeApiEnabled

/** Recent answers, so retyping or backspacing doesn't ask again. */
const cache = new Map<string, SuggestionResults>()
const CACHE_SIZE = 50

const normalize = (query: string) => query.trim().replace(/\s+/g, ' ').toLowerCase()

function toSuggestion(product: ApiProduct): ProductSuggestion {
  const slug = product.customSlug || product.autogeneratedSlug || 'product'
  return {
    id: product.id,
    name: product.name,
    // Lightspeed shows variants as "1005290 - Base"; the base SKU is what people know.
    sku: (product.sku ?? '').replace(/\s*-\s*Base$/i, ''),
    price: product.defaultDisplayedPriceFormatted ?? '',
    inStock: product.inStock !== false,
    image: product.smallThumbnailUrl || product.thumbnailUrl || '',
    route: `#!/${encodeURIComponent(slug)}/p/${product.id}`,
  }
}

/**
 * Products matching what's typed so far, best match first. Resolves to null
 * when suggestions are switched off. Rejects with an AbortError when `signal`
 * is aborted (the visitor kept typing).
 */
export async function searchProducts(query: string, signal?: AbortSignal): Promise<SuggestionResults | null> {
  if (!suggestionsEnabled) return null
  const key = normalize(query)
  if (key.length < MIN_QUERY_LENGTH) return { total: 0, items: [] }

  const cached = cache.get(key)
  if (cached) return cached

  const data = await storeApiGet<{ total?: number; items?: ApiProduct[] }>(
    'products',
    { keyword: key, enabled: 'true', limit: String(SUGGESTION_LIMIT), responseFields: FIELDS },
    signal,
  )
  const results: SuggestionResults = {
    total: data.total ?? 0,
    // The API sometimes returns more than `limit`; keep the list short.
    items: (data.items ?? []).slice(0, SUGGESTION_LIMIT).map(toSuggestion),
  }

  cache.set(key, results)
  if (cache.size > CACHE_SIZE) cache.delete(cache.keys().next().value as string)
  return results
}
