/*
 * Turns Lightspeed's records into the rows of the store's own tables
 * (db/004_catalog.sql, db/005_customers_pricing.sql). Pure functions: no
 * network, no database, so tests/lightspeedImport.test.mjs can run them.
 * scripts/import-lightspeed.mjs does the reading and writing.
 *
 * Two Lightspeed systems feed the import:
 *   Retail (the POS) — the source of truth for products, variants, prices,
 *                      stock, customers, groups and price books.
 *   eCom             — what the website adds: which products are shown,
 *                      categories, slugs, SEO text and photos. Its products
 *                      and variants carry the Retail id as externalReferenceId.
 *
 * In Retail a product family is a parent row plus child rows; every row,
 * the parent included, is one sellable variant.
 */

type Json = Record<string, unknown>

