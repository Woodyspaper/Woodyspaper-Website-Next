export type CatalogInput = {
  retailProducts: RetailProduct[]
  retailBrands: { id: string; name?: string; deleted_at?: string | null }[]
  retailInventory: { product_id: string; current_amount?: number | null; reorder_point?: number | null; deleted_at?: string | null }[]
  ecomProducts: EcomProduct[]
  ecomCategories: EcomCategory[]
  /** eCom category ids kept but not listed on the site. */
  hiddenCategoryIds?: number[]
}

/** "FINE ART PAPER & Stationery" → "fine-art-paper-stationery". */
export function slugify(text: string): string {
  return text
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/** Hands out slugs, adding a suffix when one is already taken. */
function slugPool() {
  const used = new Set<string>()
  return (wanted: string, suffix: string): string => {
    let slug = wanted || slugify(suffix) || 'item'
    if (used.has(slug)) slug = `${slug}-${slugify(suffix)}`
    for (let n = 2; used.has(slug); n++) slug = `${wanted}-${slugify(suffix)}-${n}`
    used.add(slug)
    return slug
  }
}

const text = (value: unknown, max: number): string | null => {
  if (typeof value !== 'string') return null
  const trimmed = value.trim()
  return trimmed ? trimmed.slice(0, max) : null
}

const amount = (value: unknown): number | null => (typeof value === 'number' && Number.isFinite(value) ? value : null)

const httpsUrl = (value: unknown): string | null =>
  typeof value === 'string' && value.startsWith('https://') && value.length <= 400 ? value : null

const date = (value: unknown): Date | null => {
  if (typeof value !== 'string') return null
  const parsed = new Date(value)
  return Number.isNaN(parsed.getTime()) ? null : parsed
}

export function buildCatalog(input: CatalogInput) {
  const hidden = new Set(input.hiddenCategoryIds ?? [])
  const real = input.retailProducts.filter((p) => !p.deleted_at && p.source !== 'SAMPLE' && p.sku)
  const ecomByRetailId = new Map(input.ecomProducts.filter((p) => p.externalReferenceId).map((p) => [p.externalReferenceId as string, p]))
  const combinationByRetailId = new Map<string, EcomCombination>()
  for (const product of input.ecomProducts) {
    for (const combination of product.combinations ?? []) {
      if (combination.externalReferenceId) combinationByRetailId.set(combination.externalReferenceId, combination)
    }
  }

  // Brands
  const brandSlug = slugPool()
  const brands = input.retailBrands
    .filter((b) => !b.deleted_at && text(b.name, 100))
    .map((b) => ({ retailId: b.id, name: text(b.name, 100) as string, slug: brandSlug(slugify(b.name ?? ''), b.id) }))
  const brandIds = new Set(brands.map((b) => b.retailId))

  // Categories (eCom holds the tree, slugs and images; each maps to a Retail product type)
  const categorySlug = slugPool()
  const categories = input.ecomCategories.map((c) => ({
    ecwidCategoryId: c.id,
    parentEcwidCategoryId: c.parentId || null,
    name: text(c.name, 200) ?? `Category ${c.id}`,
    slug: categorySlug(c.customSlug || c.autogeneratedSlug || slugify(c.name ?? ''), String(c.id)),
    sortOrder: c.orderBy ?? 0,
    isEnabled: c.enabled !== false,
    isHidden: hidden.has(c.id),
    imageSourceUrl: httpsUrl(c.originalImageUrl) ?? httpsUrl(c.imageUrl),
    retailId: text(c.externalReferenceId, 40),
  }))
  const categoryIds = new Set(categories.map((c) => c.ecwidCategoryId))
  const categoryByRetailId = new Map(categories.filter((c) => c.retailId).map((c) => [c.retailId as string, c.ecwidCategoryId]))

  // Products and variants
  const childrenByParent = new Map<string, RetailProduct[]>()
  for (const row of real) {
    if (!row.variant_parent_id) continue
    const list = childrenByParent.get(row.variant_parent_id) ?? []
    list.push(row)
    childrenByParent.set(row.variant_parent_id, list)
  }
  const stock = new Map<string, { qty: number; reorderPoint: number | null }>()
  for (const row of input.retailInventory) {
    if (row.deleted_at) continue
    const entry = stock.get(row.product_id) ?? { qty: 0, reorderPoint: null }
    entry.qty += Math.trunc(amount(row.current_amount) ?? 0)
    entry.reorderPoint = amount(row.reorder_point) ?? entry.reorderPoint
    stock.set(row.product_id, entry)
  }

  const productSlug = slugPool()
  const products = []
  const variants = []
  const variantOptions = []
  const productCategories = []
  const images = []
  const inventory = []

  for (const parent of real) {
    if (parent.variant_parent_id) continue
    const ecom = ecomByRetailId.get(parent.id)
    const name = text(ecom?.name, 300) ?? text(parent.name, 300) ?? (parent.sku as string)
    const tags = (ecom?.attributes ?? []).filter((a) => a.type === 'TAGS' && a.value).map((a) => a.value as string)

    let categoryList = (ecom?.categoryIds ?? []).filter((id) => categoryIds.has(id))
    if (!categoryList.length && parent.product_type_id && categoryByRetailId.has(parent.product_type_id)) {
      categoryList = [categoryByRetailId.get(parent.product_type_id) as number]
    }
    const defaultCategory = ecom?.defaultCategoryId && categoryIds.has(ecom.defaultCategoryId) ? ecom.defaultCategoryId : (categoryList[0] ?? null)

    products.push({
      retailId: parent.id,
      ecwidProductId: ecom?.id ?? null,
      name,
      slug: productSlug(ecom?.customSlug || ecom?.autogeneratedSlug || slugify(name), parent.sku as string),
      descriptionHtml: text(ecom?.description, 1_000_000) ?? text(parent.description, 1_000_000),
      brandRetailId: parent.brand_id && brandIds.has(parent.brand_id) ? parent.brand_id : null,
      // What the website shows today: eCom's switch when the product is there.
      isEnabled: ecom ? ecom.enabled === true : parent.active === true && parent.ecwid_enabled_webstore === true,
      defaultEcwidCategoryId: defaultCategory,
      seoTitle: text(ecom?.seoTitle, 300),
      seoDescription: text(ecom?.seoDescription, 100_000),
      searchTags: tags.length ? tags.join(', ') : null,
      sourceUpdatedAt: date(parent.updated_at),
    })
    for (const id of new Set(categoryList)) productCategories.push({ productRetailId: parent.id, ecwidCategoryId: id })

    const family = [parent, ...(childrenByParent.get(parent.id) ?? [])]
    const defaultRetailId =
      family.find((row) => combinationByRetailId.get(row.id)?.id === ecom?.defaultCombinationId && ecom?.defaultCombinationId)?.id ?? parent.id
    const seenImages = new Set<string>()

    for (const image of [...(ecom?.media?.images ?? [])].sort((a, b) => (a.orderBy ?? 0) - (b.orderBy ?? 0))) {
      const sourceUrl = httpsUrl(image.image1500pxUrl) ?? httpsUrl(image.imageOriginalUrl)
      if (!sourceUrl || seenImages.has(sourceUrl)) continue
      seenImages.add(sourceUrl)
      images.push({ productRetailId: parent.id, variantRetailId: null as string | null, sortOrder: image.orderBy ?? 0, sourceUrl, thumbSourceUrl: httpsUrl(image.image400pxUrl) })
    }

    for (const row of family) {
      const combination = combinationByRetailId.get(row.id)
      const options = []
      const seenNames = new Set<string>()
      for (const option of row.variant_options ?? []) {
        const optionName = text(option.name, 60)?.toUpperCase()
        const value = text(option.value, 200)
        if (!optionName || !value || seenNames.has(optionName)) continue
        seenNames.add(optionName)
        options.push({ variantRetailId: row.id, name: optionName, value, sortOrder: options.length })
      }
      variantOptions.push(...options)

      const barcode = ['UPC', 'EAN', 'ITF'].map((type) => (row.product_codes ?? []).find((c) => c.type === type)?.code).find(Boolean)
      const inches = row.dimensions_unit === 'IN'
      variants.push({
        retailId: row.id,
        productRetailId: parent.id,
        ecwidCombinationId: combination?.id ?? null,
        sku: text(row.sku, 100) as string,
        name: options.map((o) => o.value).join(' / ').slice(0, 300),
        price: amount(row.price_excluding_tax) ?? 0,
        cost: amount(row.supply_price),
        supplierCode: text(row.supplier_code, 100),
        barcode: text(barcode, 60),
        weightLb: row.weight_unit === 'LB' ? amount(row.weight) : null,
        lengthIn: inches ? amount(row.length) : null,
        widthIn: inches ? amount(row.width) : null,
        heightIn: inches ? amount(row.height) : null,
        isDefault: row.id === defaultRetailId,
        isEnabled: row.active === true,
        sortOrder: combination?.orderBy ?? row.button_order ?? 0,
      })

      const onHand = stock.get(row.id)
      inventory.push({ variantRetailId: row.id, qtyOnHand: onHand?.qty ?? 0, trackStock: row.has_inventory !== false, reorderPoint: onHand?.reorderPoint ?? null })

      const sourceUrl = httpsUrl(combination?.imageUrl)
      if (sourceUrl && !seenImages.has(sourceUrl)) {
        seenImages.add(sourceUrl)
        images.push({ productRetailId: parent.id, variantRetailId: row.id, sortOrder: 100 + (combination?.orderBy ?? 0), sourceUrl, thumbSourceUrl: httpsUrl(combination?.thumbnailUrl) })
      }
    }
  }

  return { brands, categories, products, variants, variantOptions, productCategories, images, inventory }
}

export type RetailCustomer = Json & { id: string; customer_group_id?: string | null; deleted_at?: string | null }

export type CustomersInput = {
  retailGroups: { id: string; name?: string; deleted_at?: string | null }[]
  retailCustomers: RetailCustomer[]
  ecomGroups: { id: number; externalReferenceId?: string }[]
}

const COUNTRY_NAMES: Record<string, string> = { 'US VIRGIN ISLANDS': 'VI', 'UNITED STATES': 'US', USA: 'US' }

function countryCode(value: unknown): string | null {
  const raw = text(value, 60)?.toUpperCase()
  if (!raw) return null
  if (/^[A-Z]{2}$/.test(raw)) return raw
  return COUNTRY_NAMES[raw] ?? null
}

export function buildCustomers(input: CustomersInput) {
  const ecomGroupByRetailId = new Map(input.ecomGroups.filter((g) => g.externalReferenceId).map((g) => [g.externalReferenceId as string, g.id]))
  const groups = input.retailGroups
    .filter((g) => !g.deleted_at)
    .map((g) => ({ retailId: g.id, name: text(g.name, 200) ?? g.id, ecwidGroupId: ecomGroupByRetailId.get(g.id) ?? null }))
  const groupIds = new Set(groups.map((g) => g.retailId))

  const customers = []
  const addresses = []
  for (const c of input.retailCustomers) {
    if (c.deleted_at) continue
    const firstName = text(c.first_name, 100)
    const lastName = text(c.last_name, 100)
    customers.push({
      retailId: c.id,
      customerCode: text(c.customer_code, 60),
      email: text(c.email, 254)?.toLowerCase() ?? null,
      name: text(c.name, 200) ?? ([firstName, lastName].filter(Boolean).join(' ') || null),
      firstName,
      lastName,
      companyName: text(c.company_name, 200),
      phone: text(c.phone, 50),
      mobile: text(c.mobile, 50),
      groupRetailId: c.customer_group_id && groupIds.has(c.customer_group_id) ? c.customer_group_id : null,
      onAccountLimit: amount(c.on_account_limit),
      staffNotes: text(c.note, 100_000),
      sourceUpdatedAt: date(c.updated_at),
    })
    for (const [kind, prefix] of [['billing', 'postal'], ['shipping', 'physical']] as const) {
      const address = {
        customerRetailId: c.id,
        kind,
        street1: text(c[`${prefix}_address_1`], 300),
        street2: text(c[`${prefix}_address_2`], 300),
        city: text(c[`${prefix}_city`], 100),
        stateCode: text(c[`${prefix}_state`], 20)?.toUpperCase() ?? null,
        postalCode: text(c[`${prefix}_postcode`], 20),
        countryCode: countryCode(c[`${prefix}_country_id`]),
      }
      if (address.street1 || address.city || address.postalCode) addresses.push(address)
    }
  }
  return { groups, customers, addresses }
}

export type PricingInput = {
  priceBooks: {
    id: string
    name?: string
    type?: string
    customer_group_id?: string | null
    restrict_to_platform_label?: string | null
    valid_from?: string | null
    valid_to?: string | null
    deleted_at?: string | null
  }[]
  priceBookProducts: {
    price_book_id: string
    product_id: string
    price?: number | null
    min_units?: number | null
    max_units?: number | null
    version?: number
    deleted_at?: string | null
  }[]
  promotions: {
    name?: string
    status?: string
    start_time?: string | null
    end_time?: string | null
    /** Where Lightspeed applies it: "Register", "Ecommerce". Missing or empty means everywhere. */
    channels?: string[] | null
    use_promo_code?: boolean
    customer_group_ids?: string[]
    action?: { type?: string; value?: number }
    condition?: { include?: unknown[]; exclude?: { field?: string; value?: string }[] }
  }[]
  /** Retail ids of the variants being imported; price lines for anything else are dropped. */
  variantRetailIds: Set<string>
  /** The moment the import runs, for price books with start and end dates. Defaults to now. */
  now?: Date
}

/** Lightspeed's label for a price book that is for the shop counter only. */
export const isInStoreOnly = (platformLabel: string | null | undefined): boolean => /^\s*in[\s-]*store\s*$/i.test(platformLabel ?? '')

/**
 * A price book with dates applies from valid_from up to valid_to; a missing
 * date leaves that side open. A date that can't be read counts as not valid,
 * so a book is never applied outside the dates someone meant to give it.
 */
function validOn(book: { valid_from?: string | null; valid_to?: string | null }, now: Date): boolean {
  for (const [value, isStart] of [[book.valid_from, true], [book.valid_to, false]] as const) {
    if (value == null || value === '') continue
    const at = date(value)
    if (!at) return false
    if (isStart ? at.getTime() > now.getTime() : at.getTime() < now.getTime()) return false
  }
  return true
}

export function buildPricing(input: PricingInput) {
  const now = input.now ?? new Date()
  // The BASE book is the list price itself, which the variants already carry.
  const current = input.priceBooks.filter((b) => !b.deleted_at && b.type !== 'BASE')
  // A book whose dates don't cover today is left out with all its lines, so its
  // customers fall back to their group discount or the list price.
  const books = current.filter((b) => validOn(b, now))
  const notValidBookIds = new Set(current.filter((b) => !validOn(b, now)).map((b) => b.id))
  // "In Store" books are imported with their lines but marked: whether they
  // apply on the website is decided where prices are worked out (pricing/prices.ts).
  const priceLists = books.map((b) => ({
    retailId: b.id,
    name: text(b.name, 200) ?? b.id,
    platform: text(b.restrict_to_platform_label, 40),
    inStoreOnly: isInStoreOnly(b.restrict_to_platform_label),
  }))
  const bookIds = new Set(books.map((b) => b.id))

  const skipped = { otherBook: 0, notValidToday: 0, unknownProduct: 0, zeroPrice: 0, badQuantity: 0, duplicate: 0 }
  type Line = { priceListRetailId: string; variantRetailId: string; price: number; minQty: number; maxQty: number | null; version: number }
  const latest = new Map<string, Line>()
  for (const line of input.priceBookProducts) {
    if (!line.deleted_at && notValidBookIds.has(line.price_book_id)) { skipped.notValidToday++; continue }
    if (line.deleted_at || !bookIds.has(line.price_book_id)) { skipped.otherBook++; continue }
    if (!input.variantRetailIds.has(line.product_id)) { skipped.unknownProduct++; continue }
    const price = amount(line.price)
    // A zero line would hand the product out for free; the customer falls back to their group or list price.
    if (price == null || price <= 0) { skipped.zeroPrice++; continue }
    // Quantity breaks: the price holds from minQty up to maxQty units of the
    // product (no upper end when maxQty is null). No break at all is 1 and up.
    const minQty = Math.max(1, Math.ceil(amount(line.min_units) ?? 1))
    const maxUnits = amount(line.max_units)
    const maxQty = maxUnits == null ? null : Math.floor(maxUnits)
    if (maxQty != null && maxQty < minQty) { skipped.badQuantity++; continue }
    const key = `${line.price_book_id}|${line.product_id}|${minQty}`
    const previous = latest.get(key)
    if (previous) skipped.duplicate++
    if (!previous || (line.version ?? 0) > previous.version) {
      latest.set(key, { priceListRetailId: line.price_book_id, variantRetailId: line.product_id, price, minQty, maxQty, version: line.version ?? 0 })
    }
  }
  const priceListItems = [...latest.values()].map(({ priceListRetailId, variantRetailId, price, minQty, maxQty }) => ({ priceListRetailId, variantRetailId, price, minQty, maxQty }))
  const bookCounts = {
    notValidToday: notValidBookIds.size,
    inStoreOnly: priceLists.filter((l) => l.inStoreOnly).length,
    quantityBreakLines: priceListItems.filter((i) => i.minQty > 1 || i.maxQty != null).length,
  }

  // A group's price list: the book attached to it. Should a group have two,
  // one that applies on every platform is preferred to an "In Store" one.
  const groupPriceLists = new Map<string, string>()
  for (const book of [...books].sort((a, b) => Number(isInStoreOnly(a.restrict_to_platform_label)) - Number(isInStoreOnly(b.restrict_to_platform_label)))) {
    if (book.customer_group_id && !groupPriceLists.has(book.customer_group_id)) groupPriceLists.set(book.customer_group_id, book.id)
  }

  // Percent-off promotions tied to customer groups, with the product types they leave out.
  const groupDiscounts = new Map<string, { percent: number; name: string | null; excludedCategoryRetailIds: string[] }>()
  for (const promotion of input.promotions) {
    if (promotion.status !== 'active' || promotion.use_promo_code) continue
    // Not started yet, already over, or for the shop counter only: not a website discount.
    if (!validOn({ valid_from: promotion.start_time, valid_to: promotion.end_time }, now)) continue
    if (promotion.channels?.length && !promotion.channels.some((channel) => /^e-?commerce$/i.test(channel))) continue
    if (promotion.action?.type !== 'basic_percent_discount' || (promotion.condition?.include ?? []).length) continue
    const percent = Math.round((amount(promotion.action.value) ?? 0) * 100_000) / 1000
    if (!(percent > 0 && percent < 100)) continue
    const excluded = (promotion.condition?.exclude ?? []).filter((e) => e.field === 'type_id' && e.value).map((e) => e.value as string)
    for (const groupId of promotion.customer_group_ids ?? []) {
      const current = groupDiscounts.get(groupId)
      if (!current || percent > current.percent) {
        groupDiscounts.set(groupId, { percent, name: text(promotion.name, 200), excludedCategoryRetailIds: excluded })
      }
    }
  }

  return { priceLists, priceListItems, groupPriceLists, groupDiscounts, skipped, bookCounts }
}
